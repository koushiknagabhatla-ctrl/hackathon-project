function levenshteinDistance(a: string, b: string): number {
  const m = a.length;
  const n = b.length;
  const dp: number[][] = Array.from({ length: m + 1 }, () => Array(n + 1).fill(0));

  for (let i = 0; i <= m; i++) dp[i][0] = i;
  for (let j = 0; j <= n; j++) dp[0][j] = j;

  for (let i = 1; i <= m; i++) {
    for (let j = 1; j <= n; j++) {
      const cost = a[i - 1] === b[j - 1] ? 0 : 1;
      dp[i][j] = Math.min(
        dp[i - 1][j] + 1,
        dp[i][j - 1] + 1,
        dp[i - 1][j - 1] + cost,
      );
    }
  }
  return dp[m][n];
}

/**
 * Typo-Tolerant Pattern Analyzer & "Did You Mean?" Suggester.
 * Analyzes misspelled search inputs and recommends closest Andhra Pradesh city.
 */
export function getSuggestedCity(query: string): IndiaLocation | null {
  if (!query || query.trim().length < 3) return null;
  const clean = query.trim().toLowerCase();

  // 1. Direct colloquial alias / historical name match
  const aliasTargetId = CITY_ALIASES[clean];
  if (aliasTargetId) {
    const found = AP_LOCATIONS.find((l) => l.id === aliasTargetId);
    if (found) return found;
  }

  // 2. If exact matches exist, no typo suggestion needed
  const exactMatches = AP_LOCATIONS.filter(
    (l) =>
      l.name.toLowerCase().includes(clean) ||
      l.district.toLowerCase().includes(clean) ||
      l.region.toLowerCase().includes(clean),
  );
  if (exactMatches.length > 0) return null;

  // 3. Levenshtein distance pattern analysis
  let bestMatch: IndiaLocation | null = null;
  let minDistance = Infinity;

  for (const loc of AP_LOCATIONS) {
    const locName = loc.name.toLowerCase();
    const dist = levenshteinDistance(clean, locName);

    const threshold = clean.length <= 4 ? 2 : Math.min(4, Math.floor(clean.length / 2));

    if (dist <= threshold && dist < minDistance) {
      minDistance = dist;
      bestMatch = loc;
    }
  }

  return bestMatch;
}

/**
 * Dynamic geocoding search for any Andhra Pradesh town, village, or locality.
 * Queries OpenStreetMap Nominatim scoped strictly to Andhra Pradesh, India.
 */
export async function searchIndiaLocation(query: string): Promise<IndiaLocation[]> {
  if (!query || query.trim().length < 2) return [];

  const clean = query.trim().toLowerCase();

  // 1. Fast exact matching in our comprehensive 260+ AP locations database
  const localMatches = AP_LOCATIONS.filter(
    (l) =>
      l.name.toLowerCase().includes(clean) ||
      l.district.toLowerCase().includes(clean) ||
      l.region.toLowerCase().includes(clean),
  );

  if (localMatches.length >= 3) {
    return localMatches.slice(0, 10);
  }

  // 2. Query Nominatim for rural villages / mandals in Andhra Pradesh
  try {
    const encoded = encodeURIComponent(`${query}, Andhra Pradesh, India`);
    const res = await fetch(
      `https://nominatim.openstreetmap.org/search?q=${encoded}&format=json&countrycodes=in&limit=6&addressdetails=1`,
      {
        headers: { "User-Agent": "Auralis-CivicIntelligence/1.0" },
      },
    );
    if (res.ok) {
      const data = await res.json();
      const nominatimResults: IndiaLocation[] = [];
      for (const item of data) {
        const addr = item.address || {};
        const state = addr.state || "";
        // Strict Andhra Pradesh filter
        if (state.toLowerCase().includes("andhra") || state.toLowerCase().includes("ap")) {
          const name = item.name || item.display_name.split(",")[0];
          const district = addr.county || addr.state_district || "Andhra Pradesh";
          nominatimResults.push({
            id: `ap_${item.osm_id || Math.random().toString(36).slice(2, 8)}`,
            name: name,
            state: "Andhra Pradesh",
            district: district,
            region: `${district} Mandal / Village`,
            coordinates: [parseFloat(item.lon), parseFloat(item.lat)],
            zoom: 13.5,
            cad_zone: `AP-112-${district.slice(0, 3).toUpperCase()}`,
          });
        }
      }

      // Merge and deduplicate by name
      const seen = new Set<string>();
      const combined: IndiaLocation[] = [];
      for (const loc of [...localMatches, ...nominatimResults]) {
        if (!seen.has(loc.name.toLowerCase())) {
          seen.add(loc.name.toLowerCase());
          combined.push(loc);
        }
      }
      return combined.sort((a, b) => a.name.localeCompare(b.name)).slice(0, 15);
    }
  } catch {
    // Network fallback
  }

  return localMatches.sort((a, b) => a.name.localeCompare(b.name));
}


/** District/city seats, used only to break scoring ties. */
const MAJOR_IDS = new Set([
  "visakhapatnam", "vijayawada", "guntur", "nellore", "kurnool", "rajahmundry",
  "tirupati", "kakinada", "kadapa", "anantapur", "vizianagaram", "eluru",
  "ongole", "nandyal", "machilipatnam", "adoni", "tenali", "proddatur",
  "chittoor", "hindupur", "bhimavaram", "madanapalle", "srikakulam",
  "amaravati", "tadepalligudem", "chirala", "guntakal", "dharmavaram",
]);

export interface RankedLocation {
  location: IndiaLocation;
  score: number;
  reason: "exact" | "alias" | "prefix" | "word" | "contains" | "district" | "fuzzy";
}

/**
 * Score one location against a normalised query. Higher is better, 0 = no match.
 */
function scoreLocation(loc: IndiaLocation, q: string): { score: number; reason: RankedLocation["reason"] } | null {
  const name = loc.name.toLowerCase();
  const district = loc.district.toLowerCase();
  const region = loc.region.toLowerCase();
  const bonus = MAJOR_IDS.has(loc.id) ? 12 : 0;

  if (name === q) return { score: 1000 + bonus, reason: "exact" };
  if (CITY_ALIASES[q] === loc.id) return { score: 950 + bonus, reason: "alias" };
  if (name.startsWith(q)) return { score: 800 + bonus - name.length, reason: "prefix" };

  // "gudem" should find Tadepalligudem, but rank it under a prefix hit.
  const words = name.split(/[\s\-()]+/);
  if (words.some((w) => w.startsWith(q))) {
    return { score: 600 + bonus - name.length, reason: "word" };
  }
  if (name.includes(q)) return { score: 400 + bonus - name.length, reason: "contains" };
  if (district === q) return { score: 350, reason: "district" };
  if (district.includes(q) || region.includes(q)) return { score: 200, reason: "district" };

  // Fuzzy last, and only for queries long enough for a typo to be meaningful.
  if (q.length >= 4) {
    const d = levenshteinDistance(q, name);
    const tolerance = q.length <= 5 ? 1 : q.length <= 8 ? 2 : 3;
    if (d <= tolerance) return { score: 150 - d * 10 + bonus, reason: "fuzzy" };
  }
  return null;
}

/**
 * Ranked, typo-tolerant search over every registered location.
 * Synchronous and offline: the coordinates are already on disk.
 */
export function rankedSearch(query: string, limit = 12): RankedLocation[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];

  const out: RankedLocation[] = [];
  for (const loc of AP_LOCATIONS) {
    const s = scoreLocation(loc, q);
    if (s) out.push({ location: loc, score: s.score, reason: s.reason });
  }
  out.sort((a, b) => b.score - a.score || a.location.name.localeCompare(b.location.name));
  return out.slice(0, limit);
}

/**
 * What to show before anything is typed: the nearest places to where the
 * operator already is, then major seats to fill the list.
 */
export function recommendedLocations(
  near?: IndiaLocation,
  limit = 8
): IndiaLocation[] {
  const out: IndiaLocation[] = [];

  if (near) {
    const [lon, lat] = near.coordinates;
    const byDistance = AP_LOCATIONS
      .filter((l) => l.id !== near.id)
      .map((l) => {
        const dLat = ((l.coordinates[1] - lat) * Math.PI) / 180;
        const dLon = ((l.coordinates[0] - lon) * Math.PI) / 180;
        const a =
          Math.sin(dLat / 2) ** 2 +
          Math.cos((lat * Math.PI) / 180) *
            Math.cos((l.coordinates[1] * Math.PI) / 180) *
            Math.sin(dLon / 2) ** 2;
        return { l, km: 6371 * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a)) };
      })
      .sort((x, y) => x.km - y.km)
      .slice(0, Math.ceil(limit / 2))
      .map((x) => x.l);
    out.push(...byDistance);
  }

  for (const id of MAJOR_IDS) {
    if (out.length >= limit) break;
    if (near?.id === id || out.some((l) => l.id === id)) continue;
    const found = AP_LOCATIONS.find((l) => l.id === id);
    if (found) out.push(found);
  }
  return out.slice(0, limit);
}
