def get_all_cities() -> list[IndianCity]:
    """Return all Andhra Pradesh cities sorted strictly alphabetically by name."""
    return sorted(AP_CITIES_REGISTRY, key=lambda c: c.name.lower())


def get_city_by_id(city_id: str) -> IndianCity | None:
    return AP_CITIES_MAP.get(city_id.lower().strip())


# Alias for backward compatibility
get_city = get_city_by_id


def search_cities(query: str, limit: int = 30) -> list[IndianCity]:
    """Search Andhra Pradesh cities by name, district, or region."""
    q = query.lower().strip()
    if not q:
        return get_all_cities()[:limit]

    matches = [
        c for c in AP_CITIES_REGISTRY
        if q in c.name.lower() or q in c.district.lower() or q in c.zone.lower()
    ]
    return sorted(matches, key=lambda c: c.name.lower())[:limit]


STOPWORDS = {
    "the", "and", "what", "where", "when", "which", "who", "whom", "this", "that",
    "with", "from", "for", "about", "into", "through", "during", "before", "after",
    "above", "below", "to", "in", "on", "at", "by", "live", "weather", "air", "quality",
    "hospital", "emergency", "services", "police", "fire", "incident", "incidents", "status",
    "city", "town", "mandal", "district", "near", "nearest", "find", "show", "give", "tell",
    "please", "help", "info", "information", "report", "active", "right", "now", "today"
}


def find_city_by_name(name: str) -> IndianCity | None:
    """Find an Andhra Pradesh city by exact or fuzzy name match."""
    clean = name.lower().strip()
    if not clean or clean in STOPWORDS:
        return None

    # 1. Exact match on name or ID
    for c in AP_CITIES_REGISTRY:
        if c.name.lower() == clean or c.id == clean:
            return c

    # 2. Exact word match in city name (e.g. 'Araku' -> 'Araku Valley')
    for c in AP_CITIES_REGISTRY:
        words = [w.strip("(),") for w in c.name.lower().split()]
        if clean in words:
            return c

    # 3. Substring match only for specific non-trivial search terms
    if len(clean) >= 4:
        for c in AP_CITIES_REGISTRY:
            if clean in c.name.lower() or c.name.lower() in clean:
                return c

    return None


